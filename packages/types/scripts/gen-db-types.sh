#!/usr/bin/env bash
# Regenerates src/database.ts from the linked Supabase project. --check fails when the file is stale.
set -euo pipefail
cd "$(dirname "$0")/../../.."
out=packages/types/src/database.ts
tmp=$(mktemp)
{
  echo "// Generated by packages/types/scripts/gen-db-types.sh from the linked Supabase project. Do not edit."
  echo "// Latest migration: $(ls supabase/migrations | sort | tail -1)"
  supabase gen types typescript --linked --schema public 2>/dev/null
} > "$tmp"
pnpm exec prettier --stdin-filepath "$out" < "$tmp" > "$tmp.fmt"
if [ "${1:-}" = "--check" ]; then
  diff -q "$tmp.fmt" "$out" >/dev/null || { echo "$out is stale: run pnpm gen:db-types"; exit 1; }
else
  mv "$tmp.fmt" "$out"
fi
