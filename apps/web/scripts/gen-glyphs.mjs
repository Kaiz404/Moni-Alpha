#!/usr/bin/env node
// Writes src/lib/glyphs.generated.ts: an SVG path for every MDI name the phone draws (@repo/design's
// iconNames) and every icon a category may carry (@repo/types' categoryIconNames). Category and wallet
// rows name their icon as data, so the web looks the path up by that name.
//   node apps/web/scripts/gen-glyphs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(web, '..', '..');
const mdi = createRequire(join(web, 'package.json'))('@mdi/js');

const literals = (file, name) => {
  const source = readFileSync(join(repo, file), 'utf8');
  const block = new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\]`).exec(source)?.[1] ?? '';
  return [...block.matchAll(/'([a-z0-9-]+)'/g)].map((match) => match[1]);
};
const names = [
  ...new Set([
    ...literals('packages/design/src/icons.generated.ts', 'iconNames'),
    ...literals('packages/types/src/category.ts', 'categoryIconNames'),
    // Glyphs only the web boards draw: Customise, saved views, Clear filters, sorting.
    'view-dashboard-edit-outline',
    'circle-medium',
    'filter-remove-outline',
    'bookmark-outline',
    'bookmark',
    'arrow-up-down',
    'menu-down',
    'dock-right',
    'swap-vertical',
    'table-large',
    'minus',
    'tray-arrow-down',
    'map-marker-off-outline',
    'tag-outline',
    'chevron-up',
    'check',
    // Budget and Debts: a repayment, a write-off, copying a reminder, tapping to start.
    'cash-check',
    'text-box-remove-outline',
    'content-copy',
    'gesture-tap',
    // Review: the alert bubble, ticked and part-ticked boxes, a receipt photo still on the phone.
    'bell',
    'check-bold',
    'minus-thick',
    'image-off-outline',
    // Moni chat: a draft turned down.
    'close-circle-outline',
    // Set-up, the states and the empty states (W2-Onboarding, W2-States, W2-Empty).
    'google-play',
    'keyboard-outline',
    'shield-lock-outline',
    'file-delimited-outline',
    'bell-ring-outline',
    'currency-usd',
    'robot-happy-outline',
    'cellphone-arrow-down',
    'cloud-alert-outline',
    'home-outline',
    'open-in-new',
    'alert-circle',
    'store-outline',
  ]),
].sort();
const pascal = (name) => `mdi${name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase())}`;
const rows = names.filter((name) => mdi[pascal(name)]).map((name) => `  '${name}': '${mdi[pascal(name)]}',`);
writeFileSync(
  join(web, 'src/lib/glyphs.generated.ts'),
  `// Generated by apps/web/scripts/gen-glyphs.mjs. Do not edit.\n\n/** MDI paths by the phone's kebab names, for icons that rows name as data (categories, wallets). */\nexport const GLYPHS: Readonly<Record<string, string>> = {\n${rows.join('\n')}\n};\n`,
);
console.log(`${rows.length} glyphs`);
