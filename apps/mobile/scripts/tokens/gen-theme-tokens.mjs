#!/usr/bin/env node
/**
 * Writes constants/theme-tokens.generated.ts from the `@variant light` and
 * `@variant dark` blocks in global.css, the only file that holds token values.
 * Run: pnpm --filter moni gen:tokens. With --check, exits 1 when the committed
 * file differs from a fresh run (pnpm --filter moni lint:tokens).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../..',
);
const CSS_PATH = resolve(ROOT, 'global.css');
const OUT_PATH = resolve(ROOT, 'constants/theme-tokens.generated.ts');

function readVariant(css, variant) {
  const start = css.indexOf(`@variant ${variant} {`);
  if (start === -1)
    throw new Error(`global.css has no @variant ${variant} block`);
  const end = css.indexOf('}', start);
  const tokens = new Map();
  for (const [, name, value] of css
    .slice(start, end)
    .matchAll(/--color-([\w-]+):\s*([^;]+);/g)) {
    tokens.set(name, value.trim());
  }
  return tokens;
}

function render(light, dark) {
  const names = [...light.keys()];
  const missing = [
    ...names
      .filter((name) => !dark.has(name))
      .map((name) => `dark lacks --color-${name}`),
    ...[...dark.keys()]
      .filter((name) => !light.has(name))
      .map((name) => `light lacks --color-${name}`),
  ];
  if (missing.length > 0)
    throw new Error(
      `global.css variants differ:\n${missing.join('\n')}`,
    );

  const key = (name) =>
    /^[a-z]\w*$/i.test(name) ? name : `'${name}'`;
  const map = (tokens) =>
    names
      .map((name) => `  ${key(name)}: '${tokens.get(name)}',`)
      .join('\n');
  return `// Generated by scripts/tokens/gen-theme-tokens.mjs from global.css. Do not edit.

export const themeTokenNames = [
${names.map((name) => `  '${name}',`).join('\n')}
] as const;

export type ThemeTokenName = (typeof themeTokenNames)[number];

export const lightThemeTokens: Record<ThemeTokenName, string> = {
${map(light)}
};

export const darkThemeTokens: Record<ThemeTokenName, string> = {
${map(dark)}
};
`;
}

const css = readFileSync(CSS_PATH, 'utf8');
const output = render(
  readVariant(css, 'light'),
  readVariant(css, 'dark'),
);

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT_PATH, 'utf8');
  } catch {}
  if (current !== output) {
    console.error(
      'constants/theme-tokens.generated.ts is stale. Run: pnpm --filter moni gen:tokens',
    );
    process.exit(1);
  }
  console.log('theme-tokens.generated.ts matches global.css');
} else {
  writeFileSync(OUT_PATH, output);
  console.log(`wrote ${OUT_PATH}`);
}
