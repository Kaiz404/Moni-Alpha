"""Exports the locked Cat Pebble art (catart.py) for the app.

Writes components/brand/mascot-art.generated.ts (the in-app registry) and the SVG masters in
scripts/brand/out/ that rasterize.mjs turns into assets/images/*.png. Run: pnpm --filter moni brand:assets
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import catart as C  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, 'out')
TS = os.path.join(APP, 'components', 'brand', 'mascot-art.generated.ts')

MONO_COLOR = 'currentColor'
WHITE = '#FFFFFF'
DARK_ICON = dict(tile=None, body=C.PAPER, eye=C.INK, cut=C.DARK)

# react-native-svg ignores paint-order, so each keyed paw becomes its keyline under its fill.
PAW = re.compile(r'<ellipse (cx="[^"]+" cy="[^"]+" rx="[^"]+" ry="[^"]+") fill="([^"]+)" stroke="([^"]+)" '
                 r'stroke-width="([^"]+)" paint-order="stroke"((?: transform="[^"]+")?)></ellipse>')


def split_paint_order(s):
    return PAW.sub(lambda m: (f'<ellipse {m[1]} fill="{m[3]}" stroke="{m[3]}" stroke-width="{m[4]}"{m[5]}></ellipse>'
                              f'<ellipse {m[1]} fill="{m[2]}"{m[5]}></ellipse>'), s)


def crop(mood):
    return C.MONO_VB['tall' if mood in ('celebrate', 'surprised') else 'std']


def svg(view_box, body, size=None):
    dims = f' width="{size}" height="{size}"' if size else ''
    vb = ' '.join(C._f(v) for v in view_box)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}"{dims}>{split_paint_order(body)}</svg>'


def tile(mood, radius=True):
    rx = f' rx="{C._f(240 * C.TILE_RADIUS)}"' if radius else ''
    return f'<rect width="240" height="240"{rx} fill="{C.DEEP}"></rect>{C.figure(mood, "deep")}'


def bare(mood, ground):
    return svg(crop(mood), C.figure(mood, ground, fit=1.0, lift=0))


def mono(mood, color, mask_id):
    return svg(crop(mood), C.mono_figure(mood, color, mask_id, fit=1.0, lift=0))


def inset(canvas, share, inner, background=''):
    """inner (an <svg>) centred in a canvas x canvas square, filling `share` of its side."""
    side = canvas * share
    at = (canvas - side) / 2
    placed = inner.replace('<svg xmlns="http://www.w3.org/2000/svg" ',
                           f'<svg x="{C._f(at)}" y="{C._f(at)}" width="{C._f(side)}" height="{C._f(side)}" ', 1)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {canvas} {canvas}" width="{canvas}" '
            f'height="{canvas}">{background}{placed}</svg>')


def registry():
    art = {
        'tile': {m: svg((0, 0, 240, 240), tile(m)) for m in C.MOODS},
        'light': {m: bare(m, 'none') for m in C.MOODS},
        'dark': {m: bare(m, 'dark') for m in C.MOODS},
    }
    mono_art = {m: mono(m, MONO_COLOR, f'moni-mono-{m}') for m in C.MOODS}
    brand = dict(deepMint=C.DEEP, mintKey=C.MINTKEY, paper=C.PAPER, ink=C.INK, cream=C.CREAM,
                 darkText=C.DARK_TEXT, lemon=C.LEMON, peach=C.PEACH)
    lockup = {k: v for k, v in C.LOCKUP.items()}
    j = lambda v: json.dumps(v, indent=2)
    return f"""// generated by scripts/brand/export.py, do not edit

export const MASCOT_MOODS = {json.dumps(C.MOODS)} as const;

export type MascotMood = (typeof MASCOT_MOODS)[number];

/** The cat in brand colours: `tile` is the app icon, `light` sits on cream or paper, `dark` on dark grounds. */
export const MASCOT_ART = {j(art)} as const satisfies Record<'tile' | 'light' | 'dark', Record<MascotMood, string>>;

/** The official one-colour cat. Its fill is currentColor and every cut-out is transparent. */
export const MASCOT_MONO = {j(mono_art)} as const satisfies Record<MascotMood, string>;

export const BRAND_COLORS = {j(brand)} as const;

/** Lockup ratios of the tile height H, and the wordmark's i-dot as shares of its font size. */
export const BRAND_LOCKUP = {j(lockup)} as const;

export const WORDMARK = {{ tracking: -0.035, dot: 0.17, dotTop: 0.13 }} as const;
"""


def masters():
    rounded = svg((0, 0, 240, 240), tile('neutral'))
    paper_cat = svg(crop('neutral'), C.figure('neutral', 'deep', fit=1.0, lift=0))
    white = mono('neutral', WHITE, 'm')
    return {
        # iOS masks the corners itself; Android's launcher draws the adaptive layers below.
        'icon.svg': svg((0, 0, 240, 240), tile('neutral', radius=False), 1024),
        'icon-dark.svg': svg((0, 0, 240, 240), C.figure('neutral', DARK_ICON), 1024),
        'icon-tinted.svg': inset(1024, 0.8, white),
        # Adaptive layers are 108 dp; the launcher's mask always keeps the central 66 dp.
        'adaptive-icon.svg': inset(1024, 66 / 108, paper_cat),
        'adaptive-icon-monochrome.svg': inset(1024, 66 / 108, white),
        # Android 12 shows the splash icon in a circle two thirds of its side wide.
        'splash-icon.svg': inset(1024, 0.56, paper_cat),
        # A 24 dp small icon draws inside a 20 dp live area.
        'notification-icon.svg': inset(96, 20 / 24, white),
        'favicon.svg': rounded.replace('viewBox="0 0 240 240"', 'viewBox="0 0 240 240" width="48" height="48"', 1),
    }


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


if __name__ == '__main__':
    write(TS, registry())
    for name, text in masters().items():
        write(os.path.join(OUT, name), text)
    print(f'wrote {os.path.relpath(TS, APP)} and {len(masters())} masters in {os.path.relpath(OUT, APP)}')
